"""Generate the firmware catalogue from the shared JSON + source-built images."""
import hashlib
import json
from pathlib import Path
import sys
import shutil

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'host'))
# Bind the protocol tag to the exact source and built images. A changed loader
# cannot accidentally negotiate the same tag with an older probe firmware.
catalogue=ROOT/'host/algorithms/targets.json'
raw=json.loads(catalogue.read_text(encoding='utf-8'))
for name,metadata in raw['algorithms'].items():
    folder=ROOT/'host/algorithms'/name
    metadata['sourceSha256']=hashlib.sha256((folder/'algorithm.c').read_bytes()).hexdigest()
    metadata['linkerSha256']=hashlib.sha256((folder/'algorithm.ld').read_bytes()).hexdigest()
    metadata['binarySha256']=hashlib.sha256((ROOT/'artifacts/build/flash-algorithms'/metadata['fileName']).read_bytes()).hexdigest()
updated=json.dumps(raw,indent=2)+'\n'
if catalogue.read_text(encoding='utf-8')!=updated:catalogue.write_text(updated,encoding='utf-8',newline='\n')
from rmlink_connector.target_pack import PACK,PACK_TAG,validate_algorithm


def generate():
    folder=ROOT/'artifacts/build/flash-algorithms'
    manifest={'schemaVersion':1,'pack_tag':PACK_TAG,'algorithms':{}}
    for name,meta in PACK['algorithms'].items():
        code=(folder/meta['fileName']).read_bytes()
        manifest['algorithms'][name]={'sha256':hashlib.sha256(code).hexdigest(),'bytes':len(code)}
    (folder/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    (folder/'targets.json').write_text(json.dumps(PACK,indent=2)+'\n')
    distribution=ROOT/'artifacts/build/target-pack';distribution.mkdir(parents=True,exist_ok=True)
    for name in ['manifest.json','targets.json',*(a['fileName'] for a in PACK['algorithms'].values())]:
        shutil.copyfile(folder/name,distribution/name)
    for name in PACK['algorithms']:
        shutil.copyfile(ROOT/'host/algorithms'/name/'LICENSE',distribution/(name+'-LICENSE.txt'))
    lines=['/* Generated by scripts/generate_target_pack.py; edit host/algorithms/targets.json. */',f'#define RMLINK_TARGET_PACK_TAG {PACK_TAG}u']
    for name,meta in PACK['algorithms'].items():
        code=(folder/meta['fileName']).read_bytes()
        for target in PACK['targets']:
            if target['algorithm']==name:validate_algorithm(target,code)
        lines.append(f'static const uint8_t code_{name}[]={{')
        lines.extend('    '+','.join(f'0x{x:02x}' for x in code[i:i+24])+',' for i in range(0,len(code),24))
        lines.append('};')
    for t in PACK['targets']:
        id=t['profileId']
        for field in ('ramRegions','sectors'):
            lines.append(f'static const rmlink_memory_region_t {field}_{id}[]={{'+','.join('{%su,%su}'%(r['address'],r['size']) for r in t[field])+'};')
        lines.append(f'static const uint32_t options_{id}[]={{'+','.join(f'{a}u' for a in t['optionRegisters'])+'};')
    lines.append('static const rmlink_target_profile_t rmlink_targets[]={')
    for t in PACK['targets']:
        id=t['profileId'];a=PACK['algorithms'][t['algorithm']];p=t['preflight'];l=t['loader'];e=a['entries']
        values=[id,len(t['ramRegions']),len(t['sectors']),len(t['optionRegisters']),t['corePart'],t['dpIdcode'],p['idcodeAddress'],p['deviceId'],p['flashSizeRegisterAddress'],t['flashBase'],t['flashSize'],f'ramRegions_{id}',f'sectors_{id}',f'options_{id}',l['address'],l['buffer'],l['stack'],l['stackSize'],a['pageSize'],a['staticBase'],t['eraseTimeoutMs'],t['programTimeoutMs'],e['init'],e['uninit'],e['eraseSector'],e['programPage'],e.get('verify',0xffffffff),e['bkpt'],a.get('eraseChip',0xffffffff),f'code_{t["algorithm"]}',f'sizeof(code_{t["algorithm"]})']
        lines.append('    {'+','.join(f'{v}u' if isinstance(v,int) else v for v in values)+'},')
    lines.append('};')
    (ROOT/'firmware/components/debug_probe/rmlink_target_pack_data.inc').write_text('\n'.join(lines)+'\n')
    print(f'Shared algorithm package: {len(PACK["targets"])} targets, tag={PACK_TAG:08x}')


if __name__=='__main__':generate()
