"""Embed the same independently built MIT F103 loader into the probe firmware."""
import hashlib
from pathlib import Path

root=Path(__file__).resolve().parents[1]
data=(root/'artifacts/build/flash-algorithms/stm32f103c8.bin').read_bytes()
if not 0x510<=len(data)<=0x3c00 or len(data)%4:raise ValueError('Algorithm image bounds')
lines=['/* Generated by scripts/embed_flash_algorithm.py. Do not edit bytes.',
       ' * MIT: host/algorithms/stm32f103c8/LICENSE; provenance.json pins source.',
       ' * SHA256: '+hashlib.sha256(data).hexdigest(),' */',
       'static const uint8_t rmlink_f103_algorithm[] = {']
lines.extend('    '+','.join(f'0x{b:02x}' for b in data[i:i+16])+',' for i in range(0,len(data),16))
lines.extend(['};',''])
path=root/'firmware/components/debug_probe/rmlink_f103_algorithm.inc'
text='\n'.join(lines)
if not path.exists() or path.read_text(encoding='utf-8')!=text:path.write_text(text,encoding='utf-8')
print('Embedded F103 loader:',len(data),'bytes')
